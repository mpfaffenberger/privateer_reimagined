// A single non-base nav point (kind != "jump" and base_id empty), as a name
// + world position. Used by Patrol/Scout/Attack generators to pick a target.
struct NavRef {
    std::string name;
    HMM_Vec3    pos;
};

// Every nav point in `system_id` that isn't a dockable base (jump points and
// regular nav points are both included). Patrol / Scout / Attack all reuse
// this: jump navs are valid "go visit" targets for a system-wide sweep, and
// bases are skipped because the player already interacts with them via the
// docking/comm flow, not a nav-target reach.
std::vector<NavRef> nonbase_navs(const galaxy::Galaxy& g,
                                  const std::string& system_id) {
    std::vector<NavRef> out;
    const std::string path = g.json_path_for(system_id);
    if (path.empty()) return out;
    std::optional<StarSystem> sys = load_system(path);
    if (!sys) return out;
    for (const NavPointDef& n : sys->nav_points) {
        if (!n.base_id.empty())          continue;   // it's a base — skip
        out.push_back({ n.name, n.position });
    }
    return out;
}

// Every dockable base in `system_id` except `except_base`. Reuses
// `add_bases_from_system` so the cross-system cargo case (which already
// needs a system name + jump distance) keeps a single loader path.
std::vector<DestBase> bases_in_system(const galaxy::Galaxy& g,
                                       const std::string& system_id,
                                       const std::string& except_base) {
    std::vector<DestBase> out;
    add_bases_from_system(g, system_id, except_base, /*jumps=*/0, out);
    return out;
}

// Shortest hop count from `from_sys` to `to_sys` over `g`. -1 = unreachable,
// 0 = same system. Implemented via a Dijkstra-style min-heap so a future
// weighted graph is a drop-in (today every edge is unit weight — the queue
// just degenerates into BFS). Capped at k_max_hops to bound work on an
// adversarial universe; 16 is well above the current 11-hop diameter of the
// real assets/galaxy.json with slack to spare.
//
// Public in missions.h so the navmap mission-status panel can pick a jump
// nav on the shortest path toward a cross-system cargo/bounty target.
constexpr int k_max_hops = 16;
int hops_between(const galaxy::Galaxy& g,
                 const std::string& from_sys,
                 const std::string& to_sys) {
    if (from_sys == to_sys) return 0;
    using Pair = std::pair<int, std::string>;   // (distance, system_id)
    auto cmp = [](const Pair& a, const Pair& b) { return a.first > b.first; };
    std::priority_queue<Pair, std::vector<Pair>, decltype(cmp)> pq(cmp);
    std::unordered_map<std::string, int> dist;
    pq.push({0, from_sys});
    dist[from_sys] = 0;
    while (!pq.empty()) {
        const Pair top = pq.top(); pq.pop();
        const int    d = top.first;
        const std::string& s = top.second;
        if (s == to_sys) return d;
        if (d >= k_max_hops)              continue;   // cap (don't expand past)
        if (d > dist[s])                   continue;   // stale entry
        for (const std::string& nb : g.neighbors(s)) {
            const int nd = d + 1;
            auto it = dist.find(nb);
            if (it == dist.end() || nd < it->second) {
                dist[nb] = nd;
                pq.push({nd, nb});
            }
        }
    }
    return -1;
}

// Bounty search region: the current system ("last seen") + up to 2 of its
// neighbours, chosen deterministically from `rng`. The vector size is 1..3;
// the first entry is always `system_id` itself.
std::vector<std::string> bounty_region(const galaxy::Galaxy& g,
                                       const std::string& system_id,
                                       std::mt19937_64& rng) {
    std::vector<std::string> out;
    out.push_back(system_id);                           // "last seen" is current
    std::vector<std::string> nbrs = g.neighbors(system_id);
    std::shuffle(nbrs.begin(), nbrs.end(), rng);        // deterministic for seed
    for (const std::string& nb : nbrs) {
        if (out.size() >= 3) break;
        out.push_back(nb);
    }
    return out;
}

