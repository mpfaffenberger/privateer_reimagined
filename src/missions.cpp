// Resolved string values for the catalog tokens. generate() fills one of
// these per offer and hands it to substitute() to render a briefing
// template. Pure data — no formatting logic, just already-resolved text.
struct TokenValues {
    std::string py;    // $PY  reward
    std::string en;    // $EN  enemy / target faction
    std::string cl;    // $CL  mission giver (client)
    std::string cg;    // $CG  commodity / cargo
    std::string dn;    // $DN  nav point
    std::string dn1;   // $DN1 nav point (first)
    std::string dn2;   // $DN2 nav point (second)
    std::string nn;    // $NN  nav count
    std::string db;    // $DB  destination / target base
    std::string ds;    // $DS  destination / target system
    std::string ds1;   // $DS1 system (first)
    std::string ds2;   // $DS2 system (second)
    std::string d_o;   // $DO  bounty region
    std::string d1;    // $D1  last-seen system
    std::string d2;    // $D2  last-seen alt system
    std::string bn;    // $BN  base name
    std::string sb;    // $SB  source base
    std::string ss;    // $SS  source system
};

// Replace every occurrence of each $TOKEN in `tmpl` with its resolved value.
// Longest token first (so $DN1 / $DN2 win over $DN, $DS1 / $DS2 over $DS),
// matched by a single left-to-right scan: at each '$' we try the known
// tokens longest-first and consume the first hit. Unknown $X sequences are
// copied through untouched (the caller asserts none survive). Pure — no
// global state, allocates only the result string.
std::string substitute(std::string_view tmpl, const TokenValues& v) {
    // (token, value) pairs, declared longest-first so the scan below is a
    // straight prefix test with no extra sorting at call time.
    const std::pair<std::string_view, const std::string*> table[] = {
        { "$DN1", &v.dn1 }, { "$DN2", &v.dn2 },
        { "$DS1", &v.ds1 }, { "$DS2", &v.ds2 },
        { "$PY", &v.py }, { "$EN", &v.en }, { "$CL", &v.cl }, { "$CG", &v.cg },
        { "$DN", &v.dn }, { "$NN", &v.nn }, { "$DB", &v.db }, { "$DS", &v.ds },
        { "$DO", &v.d_o }, { "$D1", &v.d1 }, { "$D2", &v.d2 },
        { "$BN", &v.bn }, { "$SB", &v.sb }, { "$SS", &v.ss },
    };

    std::string out;
    out.reserve(tmpl.size());
    for (size_t i = 0; i < tmpl.size();) {
        if (tmpl[i] == '$') {
            const std::string_view rest = tmpl.substr(i);
            bool matched = false;
            for (const auto& [tok, val] : table) {
                if (rest.substr(0, tok.size()) == tok) {
                    out += *val;
                    i += tok.size();
                    matched = true;
                    break;
                }
            }
            if (matched) continue;
        }
        out += tmpl[i++];   // ordinary char, or an unknown $X — copy through
    }
    return out;
}

