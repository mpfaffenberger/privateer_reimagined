std::vector<Mission> generate(const std::string& base_id,
                              const std::string& system_id,
                              const galaxy::Galaxy& g,
                              uint64_t seed,
                              MissionSource source) {
    std::vector<Mission> out;
    std::mt19937_64 rng(seed);

    // Shared, read-once context (pure: galaxy graph + catalogs, no globals).
    const std::string             giver    = giver_faction_of(base_id);
    const std::string             sys_name = system_display_name(g, system_id);
    const std::vector<NavRef>     navs     = nonbase_navs(g, system_id);
    const std::vector<DestBase>   dests    = collect_dest_bases(g, system_id, base_id);
    const std::vector<Commodity>& cat      = commodity::all();
    const std::vector<Faction>    outlaws  = outlaw_factions();
    // Issue #107: prefer targets the OFFERING faction is Hostile toward
    // (pirate base -> Confed/Militia/Hunter/Kilrathi, etc.). Independent or
    // unknown bases have no alignment, so fall back to the outlaw pool.
    const Faction                 giver_f  = faction::from_name(giver);
    std::vector<Faction>          targets  = (giver_f != Faction::Count)
                                                 ? hostile_targets_for(giver_f)
                                                 : std::vector<Faction>{};
    if (targets.empty()) targets = outlaws;
    const std::vector<MissionType> types   = allowed_types(source);
    if (types.empty()) return out;

    // Small rng conveniences (single rng -> same seed yields same board).
    auto uri = [&](int lo, int hi) { return std::uniform_int_distribution<int>(lo, hi)(rng); };
    auto urz = [&](size_t n)       { return std::uniform_int_distribution<size_t>(0, n - 1)(rng); };

    // $CL: half the time the offering base's own faction, half a random corp.
    auto pick_client = [&]() -> std::string {
        if (uri(0, 1) == 0 || k_corp_count == 0) return giver;
        return std::string(missions::templates::k_corp[urz(k_corp_count)]);
    };
    // $EN / target_faction: a real outlaw faction name (so kill attribution +
    // faction::from_name resolve), falling back to "pirate" if none exist.
    auto pick_outlaw = [&]() -> std::string {
        if (targets.empty()) return "pirate";
        return faction::to_name(targets[urz(targets.size())]);
    };

    // Issue #24: board offer count is FIXED per source — Mission Computer
    // shows 5, each Guild board shows 4. No more 5-8 random swing that
    // could dump 8 offers on the player at a heavy base.
    const int slots = (source == MissionSource::Computer)
                          ? k_board_size_computer
                          : k_board_size_guild;
    for (int i = 0; i < slots; ++i) {
        const MissionType t = types[urz(types.size())];

        Mission m;
        m.id            = base_id + "-" + type_short(t) + std::to_string(i);
        m.type          = t;
        m.source        = source;
        m.giver_faction = giver;

        TokenValues v;
        v.cl = pick_client();
        const std::string enemy = pick_outlaw();
        v.en = enemy;

        int     hops        = 0;
        int64_t cargo_value = 0;

        switch (t) {
            case MissionType::Patrol: {
                if (navs.empty()) continue;                 // need somewhere to patrol
                // Patrol sweeps the WHOLE system: every non-base nav point in
                // this system is a target (bases + jump gates excluded by
                // nonbase_navs()). Shuffled only so $DN1/$DN2/$DN names in the
                // briefing aren't always the same two navs.
                std::vector<NavRef> shuf = navs;
                std::shuffle(shuf.begin(), shuf.end(), rng);
                const int n = (int)shuf.size();
                for (int k = 0; k < n; ++k) m.nav_targets.push_back(shuf[k].name);
                m.nav_count      = n;
                m.target_system  = system_id;
                m.target_faction = enemy;
                hops = 0;                                    // patrol is in-system
                v.nn  = std::to_string(n);
                v.ds  = sys_name;
                v.dn  = m.nav_targets[0];
                v.dn1 = m.nav_targets[0];
                v.dn2 = (n > 1) ? m.nav_targets[1] : m.nav_targets[0];
                v.db  = base_display_name(g, system_id, base_id);
                break;
            }
            case MissionType::Scout: {
                if (navs.empty()) continue;
                const NavRef& nav = navs[urz(navs.size())];
                m.nav_targets.push_back(nav.name);
                m.target_system  = system_id;
                m.target_faction = enemy;
                hops = 0;
                v.dn = nav.name;
                v.ds = sys_name;
                break;
            }
            case MissionType::Attack: {
                if (navs.empty()) continue;
                const NavRef& nav = navs[urz(navs.size())];
                m.nav_targets.push_back(nav.name);
                m.target_system     = system_id;
                m.target_faction    = enemy;
                m.hostiles_required = uri(k_min_attack_hostiles, k_max_attack_hostiles);
                hops = 0;
                v.dn = nav.name;
                v.ds = sys_name;
                break;
            }
            case MissionType::DefendBase: {
                if (dests.empty()) continue;                // need a base to defend
                const DestBase& d = dests[urz(dests.size())];
                m.target_system     = d.system_id;
                m.target_base       = d.base_id;
                m.target_faction    = enemy;
                m.hostiles_required = uri(k_min_defend_hostiles, k_max_defend_hostiles);
                hops = hops_between(g, system_id, d.system_id);
                if (hops < 0) hops = 0;
                v.ds = d.system_name;
                v.db = d.base_name;
                const std::vector<NavRef> dnavs = nonbase_navs(g, d.system_id);
                v.dn = dnavs.empty() ? d.base_name : dnavs[0].name;
                break;
            }
            case MissionType::Bounty: {
                if (outlaws.empty()) continue;
                m.target_faction = enemy;
                // Bounty is a SINGLE named target hunted across the region —
                // never a multi-kill contract. The briefing templates' "$EN"
                // phrasing ("find it and destroy it") is singular by design.
                m.count_required = 1;
                m.bounty_region  = bounty_region(g, system_id, rng);
                m.target_system  = system_id;
                m.last_seen_system     = m.bounty_region[0];
                m.last_seen_alt_system = (m.bounty_region.size() > 1)
                                             ? m.bounty_region[1] : m.bounty_region[0];
                // hops = nearest reachable system in the hunt region.
                int best = -1;
                for (const std::string& r : m.bounty_region) {
                    const int h = hops_between(g, system_id, r);
                    if (h >= 0 && (best < 0 || h < best)) best = h;
                }
                hops = (best < 0) ? 0 : best;
                v.d_o = join_system_names(g, m.bounty_region);
                v.ds  = v.d_o;                               // bounty copy uses $DS as the region
                v.d1  = system_display_name(g, m.last_seen_system);
                v.d2  = system_display_name(g, m.last_seen_alt_system);
                break;
            }
            case MissionType::CargoDelivery: {
                if (dests.empty() || cat.empty()) continue;
                // MerchantsGuild deliveries are almost always cross-system.
                std::vector<const DestBase*> pool;
                if (source == MissionSource::MerchantsGuild)
                    for (const DestBase& d : dests) if (d.jumps > 0) pool.push_back(&d);
                if (pool.empty())
                    for (const DestBase& d : dests) pool.push_back(&d);
                const DestBase&  d     = *pool[urz(pool.size())];
                const Commodity& c     = cat[urz(cat.size())];
                const int        units = uri(k_cargo_units_min, k_cargo_units_max);
                cargo_value = (int64_t)nominal_unit_value(c.category) * units;
                hops        = d.jumps;
                m.commodity_id     = c.id;
                m.units            = units;
                m.origin_base      = base_id;
                m.dest_system      = d.system_id;
                m.dest_base        = d.base_id;
                m.dest_base_name   = d.base_name;
                m.dest_system_name = d.system_name;
                v.cg = c.label;
                v.db = d.base_name;
                v.ds = d.system_name;
                break;
            }
        }

        const int64_t reward = compute_reward(t, source, hops, cargo_value, rng);
        m.reward = reward;
        v.py = std::to_string(reward);

        const TemplatePack tp = templates_for(t);
        m.title       = substitute(tp.summary, v);
        m.description = substitute(tp.copy[urz(tp.count)], v);
        out.push_back(std::move(m));
    }

    return out;
}

void generate_board(const std::string& base_id, const std::string& system_id,
                    const galaxy::Galaxy& g) {
    // Base seed = base id hashed, XOR a slow wall-clock window — see header.
    const int64_t window = (int64_t)std::time(nullptr) / k_board_refresh_secs;
    const uint64_t base_seed = fnv1a(base_id) ^
                               ((uint64_t)window * 0x9E3779B97F4A7C15ull);

    // Generate all three source boards off the SAME base seed but with the
    // source folded in, so the Computer / Mercenaries' / Merchants' screens
    // each show a distinct (but stable-within-a-sitting) mix at this base.
    for (int s = 0; s < 3; ++s) {
        const MissionSource src  = (MissionSource)s;
        const uint64_t       seed = base_seed ^
                                    ((uint64_t)(s + 1) * 0x9E3779B97F4A7C15ull);
        g_boards[s] = generate(base_id, system_id, g, seed, src);

        std::printf("[missions] generated %zu %s missions for '%s' (system '%s', seed %llu)\n",
                    g_boards[s].size(), source_label(src), base_id.c_str(),
                    system_id.c_str(), (unsigned long long)seed);
        for (const Mission& m : g_boards[s]) {
            std::printf("[missions]   %s | %s | %lld cr\n",
                        m.id.c_str(), m.title.c_str(), (long long)m.reward);
        }
    }
    g_boards_base = base_id;
}

const std::vector<Mission>& board(MissionSource source) {
    const int s = (int)source;
    return g_boards[(s >= 0 && s < 3) ? s : 0];
}

// ---- accept / complete ------------------------------------------------------

// True when reaching this mission's objective means leaving the player's
// CURRENT system: cargo bound for another system, a defend/attack/scout/
// patrol whose action system is a neighbour, or a bounty whose hunt region
// steps beyond the current system. Drives the "need a jump drive" refusal so
// the player can't take work they physically can't reach (FAQ rule). File-
// local: it's an accept()-time policy detail, not part of the public API.
static bool mission_is_out_of_system(const PlayerState& p, const Mission& m) {
    const std::string& here = p.current_system;
    switch (m.type) {
        case MissionType::CargoDelivery:
            return !m.dest_system.empty() && m.dest_system != here;
        case MissionType::Bounty:
            for (const std::string& r : m.bounty_region)
                if (!r.empty() && r != here) return true;
            return false;
        case MissionType::Patrol:
        case MissionType::Scout:
        case MissionType::Attack:
        case MissionType::DefendBase:
            return !m.target_system.empty() && m.target_system != here;
    }
    return false;
}

bool can_accept(const PlayerState& p, const Mission& m, int capacity) {
    // Don't accept a mission the player already has on the board —
    // the board (or at least a re-rolled snapshot) may keep showing the
    // same offer while the player can re-click Accept, which would
    // otherwise double-add it.
    for (const ActiveMission& am : p.missions) {
        if (am.id == m.id) return false;
    }
    // Issue #24: 3-active cap. The Mission Computer can hold at most 3
    // active missions; further accepts are blocked at the UI layer (the
    // board still renders all offers, but Accept is greyed). We enforce
    // it here as a hard rule so a future scripted accept can't bypass it.
    if (p.missions.size() >= 3) return false;
    // Hold-space gate for deliveries: the consignment must fit on accept.
    if (m.type == MissionType::CargoDelivery &&
        player::cargo_units_used(p) + m.units > capacity)
        return false;
    // Jump-drive gate: refuse anything that lives outside the current system
    // when the player can't jump (all six types, per the out-of-system rule).
    if (!p.has_jump_drive && mission_is_out_of_system(p, m))
        return false;
    return true;
}

bool accept(PlayerState& p, const Mission& m, int capacity) {
    if (!can_accept(p, m, capacity)) {
        // Distinguish the out-of-system refusal so the player gets a comm
        // line explaining WHY (rather than a silent no-op). Hold-space and
        // duplicate-id refusals keep the existing stdout-only diagnostic.
        if (!p.has_jump_drive && mission_is_out_of_system(p, m)) {
            std::printf("[missions] ACCEPT refused: %s is out of system, no jump drive\n",
                        m.title.c_str());
            comm::push("That job's out of system — fit a jump drive first.",
                       /*taunt=*/false);
        } else {
            std::printf("[missions] ACCEPT refused: %s (hold %d/%d, needs %d)\n",
                        m.title.c_str(), player::cargo_units_used(p), capacity, m.units);
        }
        return false;
    }
    if (m.type == MissionType::CargoDelivery) {
        // Mission cargo loads at bought_at_price 0 — it isn't yours to sell at
        // a profit, it's a consignment (v1 simplification: it still occupies
        // hold space like any cargo).
        if (!player::add_cargo(p, m.commodity_id, m.units, 0, capacity)) {
            std::printf("[missions] ACCEPT failed: could not load %d %s\n",
                        m.units, m.commodity_id.c_str());
            return false;
        }
    }
    p.missions.push_back(to_active(m));

    std::printf("[missions] ACCEPT %s | %s | reward %lld | hold %d/%d\n",
                m.id.c_str(), m.title.c_str(), (long long)m.reward,
                player::cargo_units_used(p), capacity);
    comm::push("Mission accepted: " + m.title, /*taunt=*/false);
    return true;
}

// The ONE payout path. Pay the reward of the active mission at `idx`, push
// `comm_text`, log a uniform completion line, and drop the mission from the
// active list. Every completion route (cargo, bounty, and the four objective
// types) funnels through here so the credit move + logging never drift. The
// caller owns any type-specific bookkeeping (cargo removal etc.) BEFORE this.
// Returns the reward paid.
static int64_t pay_and_drop(PlayerState& p, size_t idx,
                            const std::string& comm_text) {
    const int64_t     reward = p.missions[idx].reward;
    const std::string title  = p.missions[idx].title;
    player::add_credits(p, reward);
    std::printf("[missions] COMPLETE: %s | +%lld cr | credits %lld\n",
                title.c_str(), (long long)reward, (long long)p.credits);
    comm::push(comm_text, /*taunt=*/false);
    p.missions.erase(p.missions.begin() + (long)idx);
    return reward;
}

bool complete_delivery(PlayerState& p, const std::string& mission_id,
                       const std::string& at_base) {
    for (size_t i = 0; i < p.missions.size(); ++i) {
        ActiveMission& am = p.missions[i];
        if (am.id != mission_id || am.type != (int)MissionType::CargoDelivery)
            continue;
        if (am.dest_base != at_base) {
            std::printf("[missions] DELIVER refused: %s due at '%s', you're at '%s'\n",
                        am.title.c_str(), am.dest_base.c_str(), at_base.c_str());
            return false;
        }
        // The consignment must still be aboard (can't deliver what you sold).
        if (!player::remove_cargo(p, am.commodity_id, am.units)) {
            std::printf("[missions] DELIVER refused: consignment %d %s missing from hold\n",
                        am.units, am.commodity_id.c_str());
            return false;
        }
        pay_and_drop(p, i, "Delivery confirmed. Credits transferred.");
        return true;
    }
    std::printf("[missions] DELIVER: no active delivery '%s' for base '%s'\n",
                mission_id.c_str(), at_base.c_str());
    return false;
}

bool abandon(PlayerState& p, const std::string& mission_id) {
    for (size_t i = 0; i < p.missions.size(); ++i) {
        ActiveMission& am = p.missions[i];
        if (am.id != mission_id) continue;
        if (am.type == (int)MissionType::CargoDelivery)
            player::remove_cargo(p, am.commodity_id, am.units);   // jettison
        std::printf("[missions] ABANDON %s | %s\n", am.id.c_str(), am.title.c_str());
        comm::push("Mission abandoned: " + am.title, /*taunt=*/false);
        p.missions.erase(p.missions.begin() + (long)i);
        return true;
    }
    return false;
}

// Issue #24 fail-on-land (cargo): when the player docks anywhere, drop any
// cargo consignment whose dest_base isn't this dock (cargo jettisoned, no
// reward, no comm payout). Matches the rule that landing without delivering
// fails the contract. Other (non-cargo) mission types aren't auto-failed
// here — they persist until the player delivers or manually abandons, so
// a defend/patrol can still span multiple visits.
void fail_cargo_on_dock(PlayerState& p, const std::string& at_base) {
    for (size_t i = 0; i < p.missions.size(); /* manual */) {
        ActiveMission& am = p.missions[i];
        if (am.type != (int)MissionType::CargoDelivery) { ++i; continue; }
        // Story deliveries own their failure/completion rules in campaign.cpp.
        // Keep the giver check for saves made before MissionSource::Fixer.
        if (am.source == (int)MissionSource::Fixer || am.giver_faction == "Fixer") {
            ++i;
            continue;
        }
        if (am.dest_base == at_base) { ++i; continue; }   // at target — keep
        // Off-target dock: cargo goes (jettisoned), mission fails (no reward).
        const std::string title = am.title;
        player::remove_cargo(p, am.commodity_id, am.units);
        std::printf("[missions] FAIL on dock at '%s': %s\n",
                    at_base.c_str(), title.c_str());
        comm::push("Cargo contract failed: landed at the wrong base.",
                   /*taunt=*/false);
        p.missions.erase(p.missions.begin() + (long)i);
    }
}

// ---- in-flight progress + generic completion (#13 tracker seam) -------------

bool mark_nav_reached(PlayerState& p, const std::string& mission_id,
                      size_t nav_index) {
    for (ActiveMission& am : p.missions) {
        if (am.id != mission_id) continue;
        // Tolerate a mission whose nav_done wasn't sized yet (e.g. one loaded
        // from a save predating this field): re-derive it from nav_targets.
        if (am.nav_done.size() != am.nav_targets.size())
            am.nav_done.assign(am.nav_targets.size(), (uint8_t)0);
        if (nav_index >= am.nav_done.size()) return false;
        am.nav_done[nav_index] = 1;
        std::printf("[missions] NAV reached: %s nav %zu/%zu\n",
                    am.title.c_str(), nav_index + 1, am.nav_done.size());
        return true;
    }
    return false;
}

bool complete_if_objectives_met(PlayerState& p, const std::string& mission_id) {
    for (size_t i = 0; i < p.missions.size(); ++i) {
        ActiveMission& am = p.missions[i];
        if (am.id != mission_id) continue;

        const MissionType t = (MissionType)am.type;
        bool met = false;
        switch (t) {
            case MissionType::Scout:
            case MissionType::Patrol: {
                // Done when EVERY nav is reached. Scout has exactly one; an
                // empty list (shouldn't happen) never auto-completes.
                met = !am.nav_done.empty();
                for (uint8_t d : am.nav_done) if (!d) met = false;
                break;
            }
            case MissionType::Attack:
            case MissionType::DefendBase:
                // Done when the required hostiles are cleared at the target /
                // around the base (progress counter driven by #13/#15).
                met = am.hostiles_required > 0 &&
                      am.progress >= am.hostiles_required;
                break;
            case MissionType::CargoDelivery:
            case MissionType::Bounty:
                // These settle through complete_delivery() / on_target_destroyed();
                // not this generic path.
                return false;
        }
        if (!met) return false;

        char line[160];
        std::snprintf(line, sizeof(line),
                      "%s objective complete. %lld cr transferred.",
                      type_label(t), (long long)am.reward);
        pay_and_drop(p, i, line);
        return true;
    }
    return false;
}

// ---- status / panel seam (Navmap mission status, np-19.3) -----------------
//
// Single source of truth for the per-type mission status text. Both the
// in-flight readout (#18, build_mission_objectives) and the navmap mission
// panel (this issue) call this — keeps their formatting in lockstep.

MissionStatus mission_status(const ActiveMission& am,
                             const StarSystem& sys,
                             const std::string& current_system_id) {
    MissionStatus s;
    const MissionType type = (MissionType)am.type;
    // Cargo's "where do I deliver" lives on dest_system; every other type's
    // action system lives on target_system. That's the field the panel uses
    // to decide whether to append "→ <System>" or not.
    const std::string& tgt_sys_id =
        (type == MissionType::CargoDelivery) ? am.dest_system : am.target_system;
    s.in_current_system = !tgt_sys_id.empty() && (tgt_sys_id == current_system_id);
    s.target_system.clear();
    if (!s.in_current_system && !tgt_sys_id.empty())
        s.target_system = tgt_sys_id;       // raw id; panel display-name lookup is up to it

    char buf[160];
    switch (type) {
    case MissionType::Patrol: {
        int done = 0;
        for (uint8_t d : am.nav_done) done += (d != 0);
        const int total = am.nav_targets.empty() ? am.nav_count
                                                  : (int)am.nav_targets.size();
        std::snprintf(buf, sizeof(buf), "PATROL %d/%d", done, total);
        break;
    }
    case MissionType::Scout: {
        const std::string nav = am.nav_targets.empty() ? std::string("?")
                                                       : am.nav_targets.front();
        std::snprintf(buf, sizeof(buf), "SCOUT: reach %s", nav.c_str());
        break;
    }
    case MissionType::Attack: {
        const int need = am.hostiles_required > 0 ? am.hostiles_required
                                                  : am.count_required;
        std::snprintf(buf, sizeof(buf), "ATTACK %d/%d", am.progress, need);
        break;
    }
    case MissionType::DefendBase: {
        const int need = am.hostiles_required > 0 ? am.hostiles_required
                                                  : am.count_required;
        const bool secure = (need > 0 && am.progress >= need);
        // base_label falls back to base_id when the base isn't in `sys`,
        // which is the right behavior for cross-system rows too.
        std::string nm;
        for (const NavPointDef& n : sys.nav_points)
            if (n.base_id == am.target_base && !n.name.empty()) { nm = n.name; break; }
        if (nm.empty()) nm = am.target_base;
        std::snprintf(buf, sizeof(buf), "DEFEND %s: %s",
                      nm.c_str(), secure ? "secure" : "hostiles");
        break;
    }
    case MissionType::Bounty:
        std::snprintf(buf, sizeof(buf), "BOUNTY %s %d/%d",
                      am.target_faction.c_str(), am.progress, am.count_required);
        break;
    case MissionType::CargoDelivery:
        if (s.in_current_system) {
            // Mirrors #18 verbatim ("READY TO DELIVER") so the panel and the
            // in-flight readout can't drift apart.
            std::snprintf(buf, sizeof(buf), "READY TO DELIVER");
        } else {
            // Cross-system: include the commodity and the destination base
            // id so the panel can identify it; the panel appends the
            // destination SYSTEM as a separate "→ X" line.
            std::snprintf(buf, sizeof(buf), "DELIVER %s -> %s",
                          am.commodity_id.c_str(),
                          am.dest_base.c_str());
        }
        break;
    default:
        std::snprintf(buf, sizeof(buf), "%s", am.title.c_str());
        break;
    }
    s.text = buf;
    return s;
}

// ---- mission kill progress (np-ma2.1 death pass) ----------------------------
// NOTE: this credits mission progress for the destruction of a qualifying
// target REGARDLESS of who landed the kill. That's deliberate — a third
// party stealing your bounty/hunt target must not soft-lock the contract
// (mission forces aren't replaced after combat losses). Reputation + the
// lifetime-kill scoreboard are handled separately and stay player-only.

int on_target_destroyed(PlayerState& p, Faction victim,
                        const std::string& current_system) {
    const char* victim_name = faction::to_name(victim);
    int advanced = 0;

    // A kill only counts toward a bounty hunted in one of its posted systems.
    // An empty region means "any system" (safety fallback for older saves /
    // generators that didn't stamp a region).
    auto in_region = [&](const ActiveMission& am) {
        if (am.bounty_region.empty()) return true;   // "any"
        for (const std::string& sys : am.bounty_region)
            if (sys == current_system) return true;
        return false;
    };

    for (size_t i = 0; i < p.missions.size(); /* manual */) {
        ActiveMission& am = p.missions[i];
        if (am.type != (int)MissionType::Bounty ||
            am.target_faction != victim_name ||
            am.progress >= am.count_required ||
            !in_region(am)) {
            ++i;
            continue;
        }
        ++am.progress;
        ++advanced;
        std::printf("[missions] BOUNTY progress: %s %d/%d\n",
                    am.title.c_str(), am.progress, am.count_required);
        char line[128];
        std::snprintf(line, sizeof(line), "Bounty: %s %d/%d",
                      victim_name, am.progress, am.count_required);
        comm::push(line, /*taunt=*/false);

        if (am.progress >= am.count_required) {
            char done[128];
            std::snprintf(done, sizeof(done),
                          "Bounty complete. %lld cr transferred.",
                          (long long)am.reward);
            pay_and_drop(p, i, done);   // shared payout path
            continue;   // don't advance i — we removed this entry
        }
        ++i;
    }

    // Attack / DefendBase: count the qualifying kill per-kill. The mission
    // force spawns well outside the tracker's 6km nav bubble
    // (encounters.cpp mission_spawn_point), so update_clear()'s at-nav
    // "hostiles seen" gate rarely fires — killing the spawned force is what
    // should advance progress. We do NOT settle here: the next
    // mission_tracker::tick() runs complete_if_objectives_met() (every frame
    // for attack/defend), keeping a single completion path and sidestepping
    // erase-mid-iteration hazards. (The existing update_clear() wholesale-set
    // becomes a harmless fallback: its `progress < hostiles_required` guard no
    // longer fires once per-kill has reached the target.)
    for (ActiveMission& am : p.missions) {
        const MissionType t = (MissionType)am.type;
        if (t != MissionType::Attack && t != MissionType::DefendBase) continue;
        if (am.target_faction != victim_name) continue;
        if (am.target_system != current_system) continue;
        if (am.progress >= am.hostiles_required) continue;

        ++am.progress;
        ++advanced;
        const char* tag = (t == MissionType::Attack) ? "Attack" : "Defend";
        std::printf("[missions] %s progress: %s %d/%d\n",
                    tag, am.title.c_str(), am.progress, am.hostiles_required);
        char line[128];
        std::snprintf(line, sizeof(line), "%s: %d/%d",
                      tag, am.progress, am.hostiles_required);
        comm::push(line, /*taunt=*/false);
    }
    return advanced;
}

