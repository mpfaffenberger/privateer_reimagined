// Short uppercase tag for the Mission Computer UI and headless test. Never
// nullptr — falls back to "?" for an unknown value.
const char* type_label(MissionType t) {
    switch (t) {
        case MissionType::Patrol:        return "PATROL";
        case MissionType::Scout:         return "SCOUT";
        case MissionType::Attack:        return "ATTACK";
        case MissionType::DefendBase:    return "DEFEND";
        case MissionType::Bounty:        return "BOUNTY";
        case MissionType::CargoDelivery: return "CARGO";
    }
    return "?";
}

// Display name for a mission source — feeds briefing text + any UI that
// calls out where the offer came from. Never nullptr.
const char* source_label(MissionSource s) {
    switch (s) {
        case MissionSource::Computer:         return "Mission Computer";
        case MissionSource::MercenariesGuild: return "Mercenaries Guild";
        case MissionSource::MerchantsGuild:   return "Merchants Guild";
        case MissionSource::Fixer:             return "Fixer";
    }
    return "?";
}

