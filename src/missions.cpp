// MissionSource -> src multiplier. Single source of truth so the formula
// only knows about per-type bases, not per-source strings.
double src_mult_of(MissionSource s) {
    switch (s) {
        case MissionSource::Computer:         return k_src_mult_computer;
        case MissionSource::MercenariesGuild: return k_src_mult_merc;
        case MissionSource::MerchantsGuild:   return k_src_mult_merchant;
    }
    return k_src_mult_merchant;   // safe default for an unknown enum
}

// Pure reward function. `hops` is clamped to >= 0; `cargo_value` is only
// consulted for MissionType::CargoDelivery (use 0 for everything else).
// `rng` is consumed exactly once for non-cargo types (the jitter draw).
int64_t compute_reward(MissionType type, MissionSource src, int hops,
                       int64_t cargo_value, std::mt19937_64& rng) {
    hops = (hops < 0) ? 0 : hops;                      // clamp hops >= 0

    if (type == MissionType::CargoDelivery) {
        // Cargo: handling (flat) + capped value share + per_hop, then floored.
        const int64_t handling = k_cargo_base_fee;
        int64_t value_share = (int64_t)std::llround((double)cargo_value *
                                                     k_cargo_value_margin);
        if (value_share > k_cargo_value_cap) value_share = k_cargo_value_cap;
        if (value_share < 0)                 value_share = 0;  // belt + braces
        const int64_t per_hop = k_pay_per_hop * hops;
        const int64_t total   = handling + value_share + per_hop;
        return total < k_pay_floor ? k_pay_floor : total;
    }

    // Non-cargo: jitter → ×src_mult → +per_hop → max(floor).
    const int      idx    = (int)type;                  // k_pay is 0..5
    const int64_t  base   = k_pay[idx].base;
    const int64_t  spread = k_pay[idx].spread;
    std::uniform_int_distribution<int64_t> jit(-spread, spread);
    const int64_t  jittered = base + jit(rng);
    const double   mult     = src_mult_of(src);
    // jittered is at most 11900 (=Bounty max base); *1.10 fits easily in int64
    // even at the widest jitter window, so the double multiply is safe.
    int64_t base_pay = (int64_t)std::llround((double)jittered * mult);
    if (base_pay < 0) base_pay = 0;                    // clamp negative overflow
    const int64_t per_hop = k_pay_per_hop * hops;
    int64_t total   = base_pay + per_hop;
    // Mission Computer source pays a bit less than the Mercenaries' Guild
    // (0.85 vs 1.10 source mult), but the band still sat too high in playtest,
    // so we shave a random 1750–2500 cr off every Computer offer. Floor at
    // k_pay_floor so a long-hop Computer offer can't go below 1000 cr.
    if (src == MissionSource::Computer) {
        std::uniform_int_distribution<int> cut(1750, 2500);
        total -= cut(rng);
    }
    return total < k_pay_floor ? k_pay_floor : total;
}

