// Coarse per-unit "mission value" heuristic (credits/unit) — see header. NOT
// the market price; just enough that luxury/weapons jobs pay more than ore.
int nominal_unit_value(const std::string& category) {
    if (category == "MAGIC")   return 100;
    if (category == "WEAPONS") return 80;
    if (category == "LUXURY")  return 60;
    if (category == "MEDICAL") return 55;
    if (category == "FOOD")    return 25;
    if (category == "RAWMAT")  return 20;
    return 35;   // sensible default for the other categories
}

// FNV-1a over a string — small, stable, no deps. Seeds the per-base board.
uint64_t fnv1a(const std::string& s) {
    uint64_t h = 1469598103934665603ull;
    for (unsigned char c : s) { h ^= c; h *= 1099511628211ull; }
    return h;
}

// Read the origin base's display faction from its base.json (flavour for the
// mission giver). "Independent" when absent — never fatal.
std::string giver_faction_of(const std::string& base_id) {
    const json::Value root =
        json::parse_file("assets/bases/" + base_id + "/base.json");
    if (root.is_object() && root.contains("faction")) {
        const std::string f = root["faction"].string_or("");
        if (!f.empty()) return f;
    }
    return "Independent";
}

// Append every dockable base in `system_id` (loaded fresh from its JSON) to
// `out`, tagging each with `jumps`. Skips the origin base itself.
void add_bases_from_system(const galaxy::Galaxy& g, const std::string& system_id,
                           const std::string& origin_base, int jumps,
                           std::vector<missions::DestBase>& out) {
    const std::string path = g.json_path_for(system_id);
    if (path.empty()) return;
    std::optional<StarSystem> sys = load_system(path);
    if (!sys) return;

    std::string sys_name = sys->name;
    if (const galaxy::SystemEntry* e = g.find(system_id); e && !e->display_name.empty())
        sys_name = e->display_name;

    for (const NavPointDef& nav : sys->nav_points) {
        if (!nav.dockable || nav.base_id.empty()) continue;
        if (jumps == 0 && nav.base_id == origin_base) continue;  // not to self
        out.push_back(missions::DestBase{ system_id, sys_name, nav.base_id, nav.name, jumps });
    }
}

// Every dockable base reachable from the origin, tagged with its shortest
// jump distance. Breadth-first traversal matters here: rewards scale per hop,
// so a longer non-shortest route would silently overpay the contract.
std::vector<missions::DestBase> collect_dest_bases(const galaxy::Galaxy& g,
                                         const std::string& system_id,
                                         const std::string& origin_base) {
    std::vector<missions::DestBase> out;
    std::queue<std::string> pending;
    std::unordered_map<std::string, int> distance;
    pending.push(system_id);
    distance.emplace(system_id, 0);

    while (!pending.empty()) {
        const std::string current = pending.front();
        pending.pop();
        const int jumps = distance.at(current);
        add_bases_from_system(g, current, origin_base, jumps, out);

        for (const std::string& neighbor : g.neighbors(current)) {
            if (distance.contains(neighbor)) continue;
            distance.emplace(neighbor, jumps + 1);
            pending.push(neighbor);
        }
    }
    return out;
}

// Plot-only/special factions are not ordinary contract fodder. In particular,
// the unique Steltek drone belongs to the campaign and must never appear as a
// randomly generated "rogue Steltek" bounty, attack wave, or base assault.
bool is_procedural_combat_target(Faction f) {
    return f != Faction::Steltek;
}

// Outlaw factions = those the lawful universe already distrusts (negative
// baseline-to-player). Derived from reputation data, then constrained to the
// conventional factions procedural mission boards are allowed to target.
std::vector<Faction> outlaw_factions() {
    std::vector<Faction> out;
    for (int i = 0; i < kFactionCount; ++i) {
        const Faction faction = (Faction)i;
        if (g_faction_baseline_to_player[i] < 0 &&
            is_procedural_combat_target(faction)) {
            out.push_back(faction);
        }
    }
    return out;
}

// Issue #107: factions the OFFERING base's faction views as Hostile in the
// stance matrix. Used for Attack / DefendBase / Bounty target selection so
// the contract is faction-appropriate: a pirate base offers "kill Confed",
// a Confed base offers "kill pirate", etc. — never "kill your own kind".
// Falls back to the outlaw pool for Independent / unknown bases so the
// target list is never empty.
std::vector<Faction> hostile_targets_for(Faction giver) {
    const int gi = (int)giver;
    if (gi < 0 || gi >= kFactionCount) return outlaw_factions();
    std::vector<Faction> out;
    for (int i = 0; i < kFactionCount; ++i) {
        const Faction target = (Faction)i;
        if (i == gi) continue;                       // never target self
        if (!is_procedural_combat_target(target)) continue;
        if (g_faction_stance[gi][i] == Stance::Hostile)
            out.push_back(target);
    }
    return out;
}

